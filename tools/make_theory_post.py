def render(post):
    if post['n'] == 3:
        check_sync_claims()
    S = []
    S.append('<!doctype html><html lang="ko"><meta charset="utf-8">')
    S.append('<title>이론 시리즈 초안 %02d — %s</title>' % (post['n'], post['title']))
    S.append('<style>%s</style>' % P.CSS)
    S.append('<h1>부동산 사이클 시리즈 %02d편</h1>' % post['n'])
    S.append('<p class="hint">[복사] → 스마트에디터에 붙여넣기 → 이미지 끌어놓기 → 발행. '
             '카테고리는 <b>부동산 사이클</b>, 주제는 <b>부동산</b>으로 두세요.</p>')
    S.append('<section class="draft"><h2>%s</h2>' % post['title'])
    S.append(P.rival_panel('부동산 사이클'))
    S.append(P.field('제목', 't1', P.esc(post['title']), 't'))
    # 이미지마다 사이트로 가는 문을 단다. 캡처는 삽화가 아니라 "아공맵에 오면
    # 이걸 직접 볼 수 있다"는 증거이고, 블로그의 목적이 사이트 유입이다
    # (2026-08-16 사용자). 맨 끝 링크 하나면 거기까지 읽은 사람만 넘어간다.
    # 링크를 갈라 두는 이유: 같은 곳으로 세 번 보내면 세 번째는 안 눌린다.
    _S = sync_stats()
    # 3편 동조성 문장의 값은 /cycle/ 본문 칸(D.prose)을 그대로 읽는다(전수리뷰 #77). 블로그가 다시 계산하면
    # 같은 문장('대구·부산은 0.8')이 사이트는 2위 값, 블로그는 1위 값으로 갈린다.
    D = P.cycle_d()
    pr = D['prose']
    # 4편 숫자는 데이터에서 센다. 단정이 깨지면 초안을 만들지 않는다(theory_link3 docstring).
    n4 = {}
    if post['n'] == 4:
        import theory_link3 as L3
        adv, sts = M.load()
        try:
            n4 = L3.link3_numbers(adv, sts)
        except L3.Link3DataError as e:
            # 문장 탓이 아니다 — 입력 계열이 끊겼다(전수리뷰 #73). 글쓴이에게 맞는 문장을 고치라고 안내하지 않는다.
            raise SystemExit('4편을 만들 수 없다 — %s. 다음 클라우드 배치가 전 기간을 새 기준으로 다시 받는다'
                             '(update_adv_data._basis_reason) — git pull 로 그 데이터를 받은 뒤 다시 돌린다. 로컬에서 '
                             '--heal-basic 으로 최근 달만 다시 받으면 단절이 다시 생긴다.' % e)
        except L3.Link3ClaimError as e:
            raise SystemExit('4편을 만들 수 없다 — %s. 문장을 먼저 고칠 것.' % e)
        n4['moveins'] = link('시도별 입주물량 보기', path='/moveins/', camp='moveins_from_cycle')
    elif post['n'] == 5:
        # 5편 숫자도 같은 원칙: 데이터에서 세고, 단정이 깨지면 초안을 만들지 않는다(theory_link4 docstring).
        import theory_link4 as L4
        adv, sts = M.load()
        try:
            n4 = L4.link4_numbers(adv, sts)
        except L4.Link4ClaimError as e:
            raise SystemExit('5편을 만들 수 없다 — %s. 문장을 먼저 고칠 것.' % e)
        n4['moveins'] = link('시도별 입주물량 보기', path='/moveins/', camp='moveins_from_cycle')
    elif post['n'] in (1, 2):
        n4 = link1_values(D)
        if post['n'] == 2 and not n4['l1_mid']:
            print("  ⚠ 2편 '가운데가 가장 높은 이유' 절을 뺐다 — /cycle/ 정본에서 '보통' 구간이 가장 높지 않다. 절을 다시 쓸지 정할 것.")
    body = post['body'].strip() % dict(n4, **{
        'link': link('아공맵 부동산 사이클 리포트 보기'),
        'cycle': link('고리별 검증 결과 보기'),
        'zone': link('우리 동네 공급은 어떤가 — 시도별 리포트',
                     path='/zone/', camp='zone_from_cycle'),
        # exp는 그 자체가 <p>…</p> 여러 개다. 본문 템플릿에서 <p>%(exp)s</p>로
        # 감싸면 <p> 안에 <p>가 들어가 빈 문단이 생긴다(2026-09-10 클립보드
        # 실측: <p></p><p><br></p> 가 두 군데). 감싸지 않고 넣고, 비어 있을
        # 때만 자리 표시자를 <p>로 감싼다.
        'exp': post.get('exp') or ('<p>%s</p>' % EXP_PLACEHOLDER),
        # 시도 수는 모델에서 센다 — 링크가 가리키는 /zone/ 허브와 같은 상수(M.N_SIDO)다.
        # 1·2편 본문에 '16개'가 박혀 있었다(2026-09-23 전체 점검). 3편의 곳 수는 다른 대상
        # (사이클 검증 곳 수, sync_n)이라 따로 둔다.
        'nsido': M.N_SIDO,
        # 동조성 관련 수치는 전부 사이트에서 읽어 넣는다(2026-09-12 재산정으로
        # 15곳 → 14곳, 평균 0.71 → 0.73, 서울 0.58 → 0.55로 바뀌었다).
        'sync_table': sync_table(),
        'sync_n': _S['n'],
        'sync_avg': pr['sync_mean'],
        'sync_top2': pr['sync_top2'],
        'sync_topv': pr['sync_top_v'],
        # 최저 지역 값 = 서울 값이다(3편 render 가 check_sync_claims 로 최저가 서울인지 먼저 본다)
        'sync_lowv': pr['seoul_sync'],

    })
    S.append(P.field('본문', 'b1', body))
    S.append(P.tagfield(post.get('tags', []) + TAGS))
    for f, spot in post['imgs']:
        S.append('<p class="note">📎 <code>drafts\\%s</code> → 본문의 '
                 '[여기에 %s] 자리</p>' % (f, spot))
    S.append('<p class="note">네이버는 외부 이미지 주소를 그대로 쓰지 않으므로 '
             '파일을 직접 올려야 합니다. 이미지마다 아래 캡션을 달아 주세요 — '
             '이미지만 있으면 검색이 읽을 게 없습니다.</p>')
    # 이미지를 초안 안에 싣는다(주간·지역 초안과 같은 함수, 2026-09-27).
    S.append(P.img_gallery(post['imgs']))
    S.append('</section>')
    S.append('<p class="hint">⚠️ 사이트 /cycle/ 페이지와 같은 문장을 쓰면 유사문서로 '
             '묶입니다. 고쳐 쓰실 때도 사이트 문장을 그대로 가져오지 마세요.</p>')
    # 이론 글은 특히 위험한 자리다 — 개념을 설명하다 보면 "누가 이렇게 말했다"를
    # 적고 싶어진다. 근거는 사실만으로 온전하다(2026-08-15 리뷰 지적).
    S.append(P.SOURCE_CHECK)
    S.append('<script>%s</script></html>' % P.JS)
    return '\n'.join(S)


def main(argv):
    # 편 번호는 꼭 받는다. 예전엔 인자가 없으면 1편을 만들어 theory-01.html 을 덮었다 — docstring 은 '다음 미발행 편'이라고
    # 안내하고 있었다(전수리뷰 #75).
    nums = [a for a in argv if a.isdigit()]
    if not nums:
        raise SystemExit('편 번호를 줄 것 — python tools/make_theory_post.py <편번호> [--force]')
    n = int(nums[0])
    post = next((p for p in POSTS if p['n'] == n), None)
    if not post:
        raise SystemExit('%d편은 아직 안 썼다. POSTS에 추가할 것.' % n)
    if not os.path.isdir(OUT):
        os.makedirs(OUT)
    path = os.path.join(OUT, 'theory-%02d.html' % n)
    # render 가 생성 가드로 멈출 수 있다 — 파일을 열기 전에 끝내야 기존 초안이 0바이트가 안 된다.
    html = render(post)
    # 경험 문단을 사람이 채운 초안은 덮지 않는다(전수리뷰 #75). 새 초안에는 자리 표시자가 있는데 기존 파일에 없으면
    # 사람이 채운 것이다. drafts/ 는 gitignore 라 되돌릴 데가 없다(주간 초안의 2026-08-14 사고와 같은 가드).
    if os.path.exists(path) and '--force' not in argv:
        old = io.open(path, encoding='utf-8').read()
        if EXP_PLACEHOLDER[:20] in html and EXP_PLACEHOLDER[:20] not in old:
            alt = path[:-5] + '.new.html'
            P.write_draft(alt, html)
            print('⚠ %s 는 경험 문단을 채운 흔적이 있어 그대로 뒀다. 새 초안은 %s 에 썼다. 덮어쓰려면 --force.'
                  % (os.path.basename(path), os.path.relpath(alt, ROOT)))
            return 0
    P.write_draft(path, html)
    if P.desktop_shortcut(path, P.SHORTCUTS['theory']):
        print('  바탕화면 바로가기: %s' % P.SHORTCUTS['theory'])
    print('이론 초안 생성: %s' % os.path.relpath(path, ROOT))
    print('  %s' % post['title'])
    # 열지 않는다 — 재생성이 잦다. 볼 때만 --open.
    if '--open' in argv:
        try:
            import webbrowser
            webbrowser.open('file:///' + path.replace('\\', '/'))
        except Exception:
            pass
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
