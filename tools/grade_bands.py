"""판정 등급 구간표 — 재현 스크립트 `study_grade_bands.py`가 쓰는 구간 경계의 정본(백로그 54).

⚠️ 다섯 구간은 **모든 순부족비**를 덮어야 한다. 예전 첫 구간 하한이 -9(-900%)라, 세종 초기처럼 적정물량이
작은데 준공이 몰린 표본 16개가 -900%보다 아래로 가 어느 구간에도 안 들어갔다. 그래서 구간별 n 합(496)이
표본 수(512)와 갈렸고, 문서의 '0 미만 n=211·실질 +0.25%'를 재현하지 못했다(재현은 n=195·−2.65%).
지금은 첫 구간과 마지막 구간이 열려 있어 어떤 표본도 밖으로 새지 않는다.
"""
BANDS = [('<0', float('-inf'), 0.0), ('0~0.25', 0.0, 0.25), ('0.25~0.5', 0.25, 0.5),
         ('0.5~1.0', 0.5, 1.0), ('≥1.0', 1.0, float('inf'))]


def band(ratio):
    """순부족비 → 구간 이름. 구간표가 전체 실수를 덮으므로 밖으로 새지 않는다."""
    for name, lo, hi in BANDS:
        if lo <= ratio < hi:
            return name
    raise ValueError('구간표 밖 값: %r — BANDS 가 전체를 덮게 고칠 것' % (ratio,))
